    /// <summary>Finds a palette by name, falling back to the default one.</summary>
    public static ThemePalette Find(string? name)
    {
        foreach (ThemePalette palette in Presets)
            if (string.Equals(palette.Name, name, StringComparison.OrdinalIgnoreCase)) return palette;
        return Presets[0];
    }
